    private static void put(String name, double lat, double lng) {
        REGION_COORDINATES.put(name, new Coordinate(lat, lng, name));
    }

    /**
     * 지역명으로부터 대표 중심 좌표를 산출합니다.
     * 1단계: 인메모리 행정구역 맵 매칭 (0ms)
     * 2단계: 카카오 로컬 키워드 검색 API 호출 (자연지명, 읍/면, 섬 등)
     */
    public Optional<Coordinate> resolve(String rawRegion) {
        if (rawRegion == null || rawRegion.isBlank()) {
            return Optional.empty();
        }

        String cleaned = rawRegion.trim();

        // 1단계: 인메모리 완전 일치
        if (REGION_COORDINATES.containsKey(cleaned)) {
            Coordinate c = REGION_COORDINATES.get(cleaned);
            log.info("[RegionCoordinateResolver] 인메모리 매칭 성공: '{}' -> ({}, {})", cleaned, c.latitude(), c.longitude());
            return Optional.of(c);
        }

        // 1단계 보완: 포함 매칭 (예: "남원시" -> "남원", "해남군" -> "해남")
        for (Map.Entry<String, Coordinate> entry : REGION_COORDINATES.entrySet()) {
            String key = entry.getKey();
            if (cleaned.startsWith(key) || cleaned.contains(key)) {
                Coordinate c = entry.getValue();
                log.info("[RegionCoordinateResolver] 인메모리 부분 매칭 성공: '{}' (key={}) -> ({}, {})",
                        cleaned, key, c.latitude(), c.longitude());
                return Optional.of(c);
            }
        }

        // 2단계: 카카오 로컬 검색 API 호출 (외부 네트워크 동적 폴백)
        try {
            if (kakaoLocalSearchClient != null) {
                Optional<Coordinate> kakaoCoord = kakaoLocalSearchClient.searchRegionCoordinate(cleaned);
                if (kakaoCoord.isPresent()) {
                    log.info("[RegionCoordinateResolver] 카카오 로컬 검색 매칭 성공: '{}' -> ({}, {})",
                            cleaned, kakaoCoord.get().latitude(), kakaoCoord.get().longitude());
                    return kakaoCoord;
                }
            }
        } catch (Exception e) {
            log.warn("[RegionCoordinateResolver] 카카오 로컬 검색 실패: query={}, error={}", cleaned, e.getMessage());
        }

        log.warn("[RegionCoordinateResolver] 좌표 해석 실패: '{}'", rawRegion);
        return Optional.empty();
    }
